/******************************************************************************
 *  undo.c  -  撤销 / 重做模块实现
 *
 *  快照 = 一份完整的无人机数组 D[] + 数量 N + 选中索引 S。
 *  撤销栈按顺序存"变更前的状态"，重做栈存"被撤销掉的状态"。
 *
 *  【给初学者】
 *    快照式撤销的代价是内存：一份快照 = MAX_DRONES 个 Drone 结构体。
 *    这里 UNDO_DEPTH=32，两套栈合计约几 MB，桌面程序完全可以接受。
 *    好处是代码极其简单，且天然支持任意操作，不用为每种操作单独写命令。
 ******************************************************************************/
#include "undo.h"
#include "common.h"
#include <string.h>     // memcpy

/* ---- 快照结构：一份完整场景状态 ---- */
typedef struct {
    Drone D[MAX_DRONES];    // 所有无人机
    int   N;                // 无人机数量
    int   S;                // 选中索引
} Snap;

/* ---- 撤销栈 / 重做栈（静态数组，BSS 段自动清零） ---- */
static Snap undoStack[UNDO_DEPTH];
static int  undoTop = 0;            // 撤销栈中有效快照数
static Snap redoStack[UNDO_DEPTH];
static int  redoTop = 0;            // 重做栈中有效快照数

/* ================================================================
 *  SnapSave() - 把当前全局状态保存到快照 s 中
 * ================================================================ */
static void SnapSave(Snap* s) {
    s->N = N;
    s->S = S;
    memcpy(s->D, D, sizeof(D));     // 整块复制无人机数组
}

/* ================================================================
 *  SnapLoad() - 用快照 s 覆盖当前全局状态
 * ================================================================ */
static void SnapLoad(const Snap* s) {
    N = s->N;
    S = s->S;
    memcpy(D, s->D, sizeof(D));
}

/* ================================================================
 *  UndoPush() - 记录一次变更前的状态
 *
 *  在所有会修改场景的操作（增删无人机、加航点、移动、编队等）之前调用。
 *  新的一次变更会让之前"重做"的步骤失效，所以清空重做栈。
 * ================================================================ */
void UndoPush(void) {
    /* 撤销栈满：整体前移一位，丢弃最旧的一条 */
    if (undoTop >= UNDO_DEPTH) {
        for (int i = 0; i < UNDO_DEPTH - 1; i++)
            undoStack[i] = undoStack[i + 1];
        undoTop = UNDO_DEPTH - 1;
    }

    SnapSave(&undoStack[undoTop]);  // 保存当前状态
    undoTop++;                      // 指针上移
    redoTop = 0;                    // 清空重做栈
}

/* ================================================================
 *  Undo() - 撤销一步
 *
 *  流程：先把"当前状态"存入重做栈（以便重做），
 *        再从撤销栈弹出上一份快照并恢复。
 * ================================================================ */
void Undo(void) {
    if (undoTop <= 0) return;                   // 没有可撤销的

    SnapSave(&redoStack[redoTop]);              // 当前状态 → 重做栈
    redoTop++;

    undoTop--;                                  // 撤销指针下移
    SnapLoad(&undoStack[undoTop]);              // 恢复上一份快照
}

/* ================================================================
 *  Redo() - 重做一步
 *
 *  与 Undo 对称：当前状态存回撤销栈，再从重做栈弹出恢复。
 * ================================================================ */
void Redo(void) {
    if (redoTop <= 0) return;                   // 没有可重做的

    SnapSave(&undoStack[undoTop]);              // 当前状态 → 撤销栈
    undoTop++;

    redoTop--;                                  // 重做指针下移
    SnapLoad(&redoStack[redoTop]);              // 恢复重做状态
}

/* ================================================================
 *  UndoCan() / RedoCan() - 查询是否有可撤销/重做的步骤
 * ================================================================ */
bool UndoCan(void) { return undoTop > 0; }
bool RedoCan(void) { return redoTop > 0; }
