/******************************************************************************
 *  safety.h  -  无人机安全检测模块声明
 *
 *  提供两类安全功能：
 *    1. 静态检查（编辑时）：判断坐标越界、不同无人机起点/终点是否重合
 *    2. 实时告警（播放时）：每帧检查当前位置是否越界/相撞，弹出告警
 ******************************************************************************/
#ifndef SAFETY_H
#define SAFETY_H

#include "common.h"     // 需要 Drone、Pt、bool 等类型定义

/* ============================ 函数声明 ============================ */

/* 判断一个三维点是否在允许的空域内，返回 1=在范围内, 0=越界 */
int InAirspace(Pt p);

/* 检查第 i 架无人机的起点/终点是否与其他无人机"过近"（会相撞）。
 * 发现重合则弹窗提示并返回 1，否则返回 0。 */
int CheckOverlap(int i);

/* ============================ 实时告警（弹窗） ============================ */

/* 是否正在显示实时告警弹窗 */
extern bool alertActive;

/* 实时告警内容（弹窗中显示的文字） */
extern char alertMsg[256];

/* 弹出一个安全告警弹窗（用法同 printf） */
void SetAlert(const char* fmt, ...);

/* 实时检测当前所有无人机的位置：越界或碰撞则设置告警并返回1，否则返回0 */
int LiveCheck(void);

#endif  /* SAFETY_H */
