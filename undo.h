/******************************************************************************
 *  undo.h  -  撤销 / 重做模块声明
 *
 *  采用"快照"方案：每次变更前把整个无人机数组拍一张快照存起来，
 *  撤销时恢复上一张快照。实现简单，且对所有类型的变更（增删无人机、
 *  加航点、移动、改灯光、编队变换）都通用。
 ******************************************************************************/
#ifndef UNDO_H
#define UNDO_H

#include "common.h"

#define UNDO_DEPTH 32       // 撤销/重做栈深度（最多记住 32 步）

/* 在即将发生一次变更之前调用：记录当前状态为可撤销的一步 */
void UndoPush(void);

/* 撤销：恢复到上一步（Ctrl+Z） */
void Undo(void);

/* 重做：恢复刚被撤销的一步（Ctrl+Y） */
void Redo(void);

/* 是否还有可撤销的步骤 */
bool UndoCan(void);

/* 是否还有可重做的步骤 */
bool RedoCan(void);

#endif  /* UNDO_H */
